#!/usr/bin/env python3
"""Compile OFL Fusion Pixel BDF into a deterministic BMP-only C atlas."""
import hashlib, json, re, zipfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT/'upstream/fonts/fusion-pixel-12px-monospaced-zh_hans.bdf'

def check_coverage(tables, glyphs=None):
    from validate_translations import rows
    if glyphs is None:
        glyphs={int(m[1]) for m in re.finditer(r'^ENCODING (\d+)\n(?:.*\n)*?DWIDTH (?:6|12) ',FONT.read_text(),re.M)}
    required=set(range(32,127))
    for table in ('trans','para'):
        for dst in rows(tables/f'zh_{table}.tsv').values():required.update(map(ord,dst))
    missing=sorted(required-set(glyphs))
    if missing:raise ValueError('Missing pixel glyphs: '+repr([chr(cp) for cp in missing]))
    return len(required)

def build(output):
    text = FONT.read_text()
    glyphs = {}
    for block in text.split('STARTCHAR ')[1:]:
        cp = int(re.search(r'^ENCODING ([-0-9]+)', block, re.M)[1])
        if not 0 <= cp <= 65535: continue
        w,h,ox,oy = map(int,re.search(r'^BBX ([-0-9 ]+)',block,re.M)[1].split())
        advance = int(re.search(r'^DWIDTH ([0-9]+)',block,re.M)[1])
        if advance not in (6,12): continue
        bitmap = block.split('BITMAP\n',1)[1].split('ENDCHAR',1)[0].splitlines()
        rows = [0]*12
        for y,row in enumerate(bitmap):
            sy = 10 - oy - h + y
            bits = int(row,16)
            for x in range(w):
                sx = ox+x
                if 0<=sy<12 and 0<=sx<12 and bits & (1 << (len(row)*4-1-x)):
                    rows[sy] |= 1 << sx
        glyphs[cp] = (advance,rows)
    output.mkdir(parents=True,exist_ok=True)
    header = '/* Fusion Pixel 12px, OFL-1.1; generated by tools/build_pixel_font.py. */\n'
    header += 'typedef struct { unsigned short cp; unsigned char advance; unsigned short bits[12]; } ZhPixel;\n'
    header += 'static const ZhPixel ZH_PIXEL[] = {\n'
    header += ''.join('{%d,%d,{%s}},\n'%(cp,a,','.join(map(str,b))) for cp,(a,b) in sorted(glyphs.items()))
    header += '};\n#define ZH_PIXEL_COUNT (sizeof ZH_PIXEL / sizeof ZH_PIXEL[0])\n'
    header += r'''
static const ZhPixel *ZhPixelFind(unsigned cp) {
    size_t lo=0,hi=ZH_PIXEL_COUNT;
    while(lo<hi) {size_t mid=lo+(hi-lo)/2; unsigned key=ZH_PIXEL[mid].cp;
        if(key<cp) lo=mid+1; else hi=mid;
    }
    return lo<ZH_PIXEL_COUNT && ZH_PIXEL[lo].cp==cp ? &ZH_PIXEL[lo] : NULL;
}
static void ZhPixelRaster(const ZhPixel *p, int bw, int bh, unsigned char *out) {
    int scale=bw/p->advance, other=bh/12, x,y,rw,rh,ox,oy;
    if(other<scale) scale=other;
    if(scale>=1) {rw=p->advance*scale;rh=12*scale;}
    else {rw=bw;rh=12*bw/p->advance;if(rh>bh){rh=bh;rw=p->advance*bh/12;}}
    ox=(bw-rw)/2;oy=(bh-rh)/2;
    for(y=0;y<rh;y++) for(x=0;x<rw;x++)
        out[(oy+y)*bw+ox+x] = (p->bits[y*12/rh] & (1u<<(x*p->advance/rw))) ? 255 : 0;
}
'''
    (output/'zh_pixel.h').write_text(header)
    licenses=ROOT/'fonts/licenses'
    licenses.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(ROOT/'upstream/fonts/fusion-pixel-12-bdf.zip') as z:
        for info in z.infolist():
            if info.filename.endswith('.txt'):
                target=licenses/info.filename
                target.parent.mkdir(parents=True,exist_ok=True)
                target.write_bytes(z.read(info))
    report={'font':'Fusion Pixel 12px Monospaced Simplified Chinese','version':'2026.09.25',
            'license':'OFL-1.1','source':'https://github.com/TakWolf/fusion-pixel-font',
            'bdf_sha256':hashlib.sha256(FONT.read_bytes()).hexdigest(),'bmp_glyphs':len(glyphs)}
    (ROOT/'analysis/pixel-font.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    return glyphs
if __name__=='__main__':
    print(len(build(ROOT/'build/zh-runtime')))
